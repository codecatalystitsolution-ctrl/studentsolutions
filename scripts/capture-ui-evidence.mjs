async function captureContactSheet(theme) {
  const desktopCaptures = evidence.filter(({ theme: captureTheme, viewport }) =>
    captureTheme === theme && viewport.width === 1440,
  );
  const tiles = await Promise.all(desktopCaptures.map(async ({ route, screenshot }) => {
    const image = await readFile(resolve(outputDirectory, screenshot));
    return `<figure><img src="data:image/png;base64,${image.toString('base64')}" alt="${route}"><figcaption>${route}</figcaption></figure>`;
  }));
  const contactBrowser = await chromium.launch({ headless: true });
  const page = await contactBrowser.newPage({ viewport: { width: 1600, height: 1000 } });
  await page.setContent(`<!doctype html><html><head><style>
    *{box-sizing:border-box}body{margin:0;padding:20px;background:#e8edf6;color:#172033;font:14px sans-serif}
    h1{margin:0 0 16px;font-size:22px}main{display:grid;grid-template-columns:repeat(5,minmax(0,1fr));gap:12px}
    figure{margin:0;min-width:0;background:#fff;padding:8px;border-radius:6px;box-shadow:0 2px 8px #17203322}
    img{display:block;width:100%;height:176px;object-fit:contain;background:#f5f7fb}
    figcaption{padding-top:6px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis;font-weight:600}
  </style></head><body><h1>${theme === 'light' ? 'Light' : 'Dark'} Mode · 25 routes</h1><main>${tiles.join('')}</main></body></html>`);
  await page.screenshot({ path: resolve(outputDirectory, `${theme}-routes-contact-sheet.png`), fullPage: true });
  await page.close();
  await contactBrowser.close();
}

async function capture(pageConfig, theme, viewport) {
  const context = await browser.newContext({ viewport });
  await context.addInitScript(({ storedTheme, auth }) => {
    if (!localStorage.getItem('student-solution-theme')) {
      localStorage.setItem('student-solution-theme', storedTheme);
    }
    localStorage.setItem('filecrafters-visual-test-auth', auth);
    localStorage.setItem('welcome_seen_visual-student', 'true');
  }, { storedTheme: theme, auth: pageConfig.auth });

  const page = await context.newPage();
  const pageErrors = [];
  const consoleMessages = [];
  const failedRequests = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  page.on('console', (message) => {
    if (message.type() === 'warning' || message.type() === 'error') {
      consoleMessages.push({ type: message.type(), text: message.text() });
    }
  });
  page.on('requestfailed', (request) => {
    failedRequests.push({ url: request.url(), error: request.failure()?.errorText || 'unknown' });
  });
  await page.goto(`${baseUrl}${pageConfig.route}`, { waitUntil: 'domcontentloaded' });
  if (pageConfig.selector) {
    await page.locator(pageConfig.selector).waitFor();
  } else {
    await page.getByText(pageConfig.marker, { exact: false }).first().waitFor();
  }
  await page.evaluate(() => {
    document.getAnimations().forEach((animation) => {
      if (animation.effect?.getTiming().iterations !== Infinity) animation.finish();
    });
  });

  const state = await page.evaluate(() => ({
    theme: document.body.classList.contains('app-theme-light') ? 'light' : 'dark',
    pageBackground: getComputedStyle(document.body).getPropertyValue('--bg-page').trim(),
    horizontalOverflow: document.documentElement.scrollWidth > document.documentElement.clientWidth + 1,
  }));

  if (state.theme !== theme || state.horizontalOverflow || pageErrors.length) {
    throw new Error(`${pageConfig.name} ${theme} ${viewport.width}px validation failed: ${JSON.stringify({ state, pageErrors })}`);
  }

  const filename = `${pageConfig.name}-${theme}-${viewport.width}x${viewport.height}.png`;
  await page.screenshot({ path: resolve(outputDirectory, filename), fullPage: true });
  const initialConsoleMessages = [...consoleMessages];
  const initialFailedRequests = [...failedRequests];

  const toggledTheme = theme === 'light' ? 'dark' : 'light';
  const namedToggle = page.getByRole('button', { name: `Switch to ${toggledTheme} mode` });
  const studentToggle = page.getByRole('button', { name: 'Toggle theme' });
  const toggle = await namedToggle.count() ? namedToggle : studentToggle;
  const hasThemeToggle = await toggle.count() > 0;
  if (hasThemeToggle) await toggle.click();
  if (hasThemeToggle) {
    await page.waitForFunction((expectedTheme) =>
      document.body.classList.contains(`app-theme-${expectedTheme}`), toggledTheme);
  }
  const afterToggle = await page.evaluate(() => document.body.classList.contains('app-theme-light') ? 'light' : 'dark');
  await page.reload({ waitUntil: 'domcontentloaded' });
  if (pageConfig.selector) {
    await page.locator(pageConfig.selector).waitFor();
  } else {
    await page.getByText(pageConfig.marker, { exact: false }).first().waitFor();
  }
  const afterReload = await page.evaluate(() => document.body.classList.contains('app-theme-light') ? 'light' : 'dark');

  if (hasThemeToggle && (afterToggle !== toggledTheme || afterReload !== toggledTheme)) {
    throw new Error(`${pageConfig.name} theme toggle failed: ${JSON.stringify({ theme, afterToggle, afterReload })}`);
  }
  if (!hasThemeToggle && afterReload !== theme) {
    throw new Error(`${pageConfig.name} did not preserve its inherited theme after reload`);
  }
  const interaction = await exerciseInteraction(page, pageConfig.interaction, viewport);

  evidence.push({
    route: pageConfig.route,
    theme,
    viewport,
    screenshot: filename,
    pageBackground: state.pageBackground,
    hasThemeToggle,
    afterToggle,
    afterReload,
    pageErrors,
    interaction,
    consoleMessages: initialConsoleMessages,
    failedRequests: initialFailedRequests,
  });
  await context.close();
}

async function exerciseInteraction(page, interaction, viewport) {
  if (interaction === 'profile-edit') {
    const editButton = page.getByRole('button', { name: /Edit Profile/ });
    await editButton.waitFor({ state: 'visible' });
    await editButton.click();
    const saveButton = page.getByRole('button', { name: /Save Changes/ });
    await saveButton.waitFor({ state: 'visible' });
    const editModeOpened = await saveButton.isVisible();
    await page.getByRole('button', { name: /Cancel/ }).click();
    await editButton.waitFor({ state: 'visible' });
    return { editModeOpened, cancelRestoredProfile: await page.getByRole('button', { name: /Edit Profile/ }).isVisible() };
  }

  if (interaction === 'quiz-start') {
    await page.getByRole('button', { name: /Start Quiz/ }).first().click();
    await page.waitForURL((url) => url.pathname.endsWith('/dashboard/quiz-player'));
    return { quizPlayerOpened: await page.locator('.quiz-container').isVisible() };
  }

  if (interaction === 'faq-expand') {
    const firstFaq = page.locator('.accordion-item').first();
    const initiallyOpen = await firstFaq.evaluate((element) => element.classList.contains('is-open'));
    await firstFaq.locator('.accordion-header').click();
    await page.waitForFunction((initial) =>
      document.querySelector('.accordion-item')?.classList.contains('is-open') !== initial, initiallyOpen);
    return { faqToggled: await firstFaq.evaluate((element) => element.classList.contains('is-open')) !== initiallyOpen };
  }

  if (interaction === 'order-step') {
    await page.locator('.order-layout select').first().selectOption({ label: 'Practical File' });
    return { academicDetailsShown: await page.getByText('Academic Details').isVisible() };
  }

  if (interaction === 'order-filter') {
    const search = page.getByPlaceholder('Search by ID or Name...');
    await search.fill('Jamie Patel');
    await search.press('Enter');
    await page.waitForFunction(() => document.querySelectorAll('.premium-table tbody tr').length === 1);
    const visibleRows = await page.locator('.premium-table tbody tr').count();
    await page.getByRole('button', { name: '✖' }).click();
    await page.waitForFunction(() => document.querySelectorAll('.premium-table tbody tr').length === 3);
    return { matchingRows: visibleRows, restoredRows: await page.locator('.premium-table tbody tr').count() };
  }

  if (interaction === 'student-filter') {
    const search = page.getByPlaceholder('Search students by name, email, college, ID or status');
    await search.fill('Jamie Patel');
    await search.press('Enter');
    await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 1);
    const visibleRows = await page.locator('tbody tr').count();
    return { matchingRows: visibleRows };
  }

  if (interaction === 'student-auth-lifecycle' || interaction === 'admin-auth-lifecycle') {
    if (viewport.width < 768) return { skipped: 'mobile viewport; sidebar logout is collapsed' };
    await page.setViewportSize({ width: viewport.width, height: 1400 });
    const logoutName = interaction === 'admin-auth-lifecycle' ? /Secure Logout/ : /Log Out/;
    const email = interaction === 'admin-auth-lifecycle' ? 'admin@filecrafters.in' : 'student@example.test';
    await page.getByRole('button', { name: logoutName }).click();
    await page.waitForURL((url) => url.pathname === '/login');
    await page.getByLabel('Email Address').fill(email);
    await page.getByLabel('Password').fill('VisualPass123');
    await page.getByRole('button', { name: 'Sign In' }).click();
    const expectedPath = interaction === 'admin-auth-lifecycle' ? '/admin/dashboard' : '/dashboard/home';
    await page.waitForURL((url) => url.pathname === expectedPath);
    return { logoutReturnedToLogin: true, reloginReturnedToRoleHome: true };
  }

  return null;
}